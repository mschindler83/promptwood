"""What the generator mixins (RefineMixin, SeedvrMixin) use of the ComfyGenerator they are mixed into.

At run time ComfyHost is an empty class. For the type checker it lists the attributes and methods ComfyGenerator
(client.py) provides, so the mixins can be checked on their own."""
from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path, PurePath
    from typing import Any, Callable

    class ComfyHost:
        log: Callable[[str], None]
        progress: Callable[[int, int], None] | None
        node_times: dict
        cleanup: bool
        output_dir: PurePath | None
        last_hyperflow: bool | None
        seedvr_tiled: bool
        seedvr_precision: tuple[str, ...]
        seedvr_keep_cache: bool
        _last_seedvr: bool

        def _json(self, method: str, path: str, payload: Any = None, timeout: float = ...) -> Any: ...
        def _object_info(self, node: str, fresh: bool = False) -> dict: ...
        def lora_names(self, refresh: bool = False) -> list[str]: ...
        def name_for(self, lora: str) -> str | None: ...
        def note(self, text: str) -> None: ...
        def free(self) -> bool: ...
        def check_checkpoint(self, ck: dict) -> None: ...
        def adaln_names(self, loras: list[tuple[str, str]]) -> set[str]: ...
        def free_cache(self) -> bool: ...
        def _save(self, f: dict, dest: Path) -> None: ...
        def _drop_uploads(self, uploads: list[tuple[str, Path]]) -> None: ...
        def _begin_job(self) -> None: ...
        def _run_workflow(self, wf: dict) -> dict: ...
        def upload(self, image: Path) -> str: ...
        def _first_file(self, out: dict | None) -> dict | None: ...
        def _remove(self, top: PurePath | None, f: dict, local: Path, same_size: bool = True) -> None: ...
else:
    class ComfyHost:
        pass
